use crate::worksheet::Worksheet;
use crate::quantity::{preprocess, split_top_level};
use crate::region::Region;
use regex::Regex;

pub fn generate_python(ws: &Worksheet) -> String {
    let mut code = String::new();

    code.push_str("# Auto-generated by AaiyyanMath\n");
    code.push_str("import math\n");
    code.push_str("import numpy as np\n");
    code.push_str("import matplotlib\n");
    code.push_str("matplotlib.use(\"Agg\")\n");
    code.push_str("import matplotlib.pyplot as plt\n");
    code.push_str("import pint\n\n");

    code.push_str("ureg = pint.UnitRegistry()\n");
    code.push_str("m = ureg.meter\n");
    code.push_str("s = ureg.second\n");
    code.push_str("kg = ureg.kilogram\n");
    code.push_str("A = ureg.ampere\n");
    code.push_str("K = ureg.kelvin\n");
    code.push_str("mol = ureg.mole\n");
    code.push_str("cd = ureg.candela\n");
    code.push_str("km = ureg.kilometer\n");
    code.push_str("cm = ureg.centimeter\n");
    code.push_str("mm = ureg.millimeter\n");
    code.push_str("g = ureg.gram\n");
    code.push_str("ms = ureg.millisecond\n");
    code.push_str("us = ureg.microsecond\n");
    code.push_str("ns = ureg.nanosecond\n");
    code.push_str("pi = math.pi\n");
    code.push_str("e = math.e\n\n");

    // Replacements for scipy.misc.derivative (removed in SciPy 1.12) and quad.
    // These mirror the Rust engine and work on scalars AND numpy arrays,
    // so deriv(...) inside a plot region evaluates over the whole range.
    code.push_str("def _deriv(f, x, h=1e-5):\n");
    code.push_str("    x = getattr(x, \"magnitude\", x)\n");
    code.push_str("    return (f(x + h) - f(x - h)) / (2 * h)\n\n");
    code.push_str("def _integ(f, a, b, n=1000):\n");
    code.push_str("    a = getattr(a, \"magnitude\", a)\n");
    code.push_str("    b = getattr(b, \"magnitude\", b)\n");
    code.push_str("    xs = np.linspace(a, b, n + 1)\n");
    code.push_str("    ys = f(xs) * np.ones_like(xs)\n");
    code.push_str("    h = (b - a) / n\n");
    code.push_str("    return (h / 3) * (ys[0] + ys[-1] + 4 * np.sum(ys[1:-1:2]) + 2 * np.sum(ys[2:-2:2]))\n\n");

    for (i, region) in ws.regions.iter().enumerate() {
        match region {
            Region::Text(txt) => {
                if txt.trim().is_empty() { continue; }
                for line in txt.lines() {
                    code.push_str(&format!("# {}\n", line));
                }
                code.push('\n');
            }
            Region::Math(expr) => {
                if expr.input.trim().is_empty() { continue; }
                code.push_str(&format!("# Math Region {}\n", i + 1));
                let py_input = to_python(&expr.input);

                if expr.label.trim().is_empty() {
                    code.push_str(&format!("print({})\n", py_input));
                } else {
                    code.push_str(&format!("{} = {}\n", expr.label, py_input));
                    code.push_str(&format!("print('{} =', {})\n", expr.label, expr.label));
                }
                code.push('\n');
            }
            Region::Plot(plot) => {
                if plot.expr.trim().is_empty() { continue; }
                code.push_str("# Plot Region\n");
                let var = &plot.var;

                code.push_str(&format!("{} = np.linspace({}, {}, {})\n", var, plot.x_min, plot.x_max, plot.samples));
                code.push_str(&format!("y = {}\n", to_python_ctx(&plot.expr, Some(var))));
                code.push_str("y = getattr(y, \"magnitude\", y)  # strip units for plotting\n");
                code.push_str(&format!("plt.plot({}, y)\n", var));
                code.push_str("plt.grid(True)\n");
                // Relative path: the runner sets cwd to the run dir, so the PNG lands there.
                code.push_str(&format!("plt.savefig(\"plot_{}.png\")\n", i + 1));
                code.push_str("plt.close()\n\n");
            }
        }
    }

    code
}

fn to_python(expr: &str) -> String {
    to_python_ctx(expr, None)
}

/// `plot_var` is Some(var) when generating a plot region: deriv then evaluates
/// at the linspace array itself instead of the variable's bound value.
fn to_python_ctx(expr: &str, plot_var: Option<&str>) -> String {
    let mut s = preprocess(expr);

    // 1. Expand deriv and integ to the generated helpers.
    let mut out = String::new();
    let chars: Vec<char> = s.chars().collect();
    let mut i = 0;
    while i < chars.len() {
        let current: String = chars[i..].iter().take(6).collect();
        if current == "deriv(" {
            let start = i + 6;
            let mut depth = 1;
            let mut end = start;
            for j in start..chars.len() {
                if chars[j] == '(' { depth += 1; }
                if chars[j] == ')' { depth -= 1; if depth == 0 { end = j; break; } }
            }
            let inner: String = chars[start..end].iter().collect();
            let parts = split_top_level(&inner, ',').iter().map(|s| s.trim()).collect::<Vec<_>>();
            if parts.len() == 2 {
                let var = parts[1];
                let at = if plot_var == Some(var) {
                    var.to_string()
                } else {
                    format!("globals().get(\"{}\", 0.0)", var)
                };
                out.push_str(&format!("_deriv(lambda {}: {}, {})", var, to_python_ctx(parts[0], plot_var), at));
                i = end + 1;
                continue;
            }
        } else if current == "integ(" {
            let start = i + 6;
            let mut depth = 1;
            let mut end = start;
            for j in start..chars.len() {
                if chars[j] == '(' { depth += 1; }
                if chars[j] == ')' { depth -= 1; if depth == 0 { end = j; break; } }
            }
            let inner: String = chars[start..end].iter().collect();
            let parts = split_top_level(&inner, ',').iter().map(|s| s.trim()).collect::<Vec<_>>();
            if parts.len() == 4 {
                out.push_str(&format!("_integ(lambda {}: {}, {}, {})", parts[1], to_python_ctx(parts[0], plot_var), parts[2], parts[3]));
                i = end + 1;
                continue;
            }
        }
        out.push(chars[i]);
        i += 1;
    }
    s = out;

    // 2. Convert `^` to `**`
    s = s.replace("^", "**");

    // 3. Map standard functions
    let re = Regex::new(r"\b(sin|cos|tan|asin|acos|atan|sinh|cosh|tanh|ln|log|exp|sqrt|abs|floor|ceil|round|min|max)\(").unwrap();
    s = re.replace_all(&s, |caps: &regex::Captures| {
        let func = &caps[1];
        let py_func = match func {
            "sin" => "np.sin", "cos" => "np.cos", "tan" => "np.tan",
            "asin" => "np.arcsin", "acos" => "np.arccos", "atan" => "np.arctan",
            "sinh" => "np.sinh", "cosh" => "np.cosh", "tanh" => "np.tanh",
            "ln" => "np.log", "log" => "np.log10", "exp" => "np.exp",
            "sqrt" => "np.sqrt", "abs" => "np.abs", "floor" => "np.floor",
            "ceil" => "np.ceil", "round" => "np.round",
            "min" => "np.minimum", "max" => "np.maximum",
            _ => func,
        };
        format!("{}(", py_func)
    }).to_string();

    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::expression::Expression;

    fn make_math_ws(label: &str, input: &str) -> Worksheet {
        let mut ws = Worksheet::new("Test");
        ws.regions = vec![Region::Math(Expression::new(label, input))];
        ws
    }

    #[test]
    fn test_to_python_basic_math() {
        assert_eq!(to_python("2 + 3 * 4"), "2+3*4");
        assert_eq!(to_python("a^2"), "a**2");
        assert_eq!(to_python("(a + b)^3"), "(a+b)**3");
    }

    #[test]
    fn test_to_python_units() {
        assert_eq!(to_python("5 m"), "5*m");
        assert_eq!(to_python("5 m / 2 s"), "5*m/2*s");
        assert_eq!(to_python("10 kg * 2"), "10*kg*2");
    }

    #[test]
    fn test_to_python_functions() {
        assert_eq!(to_python("sin(x)"), "np.sin(x)");
        assert_eq!(to_python("asin(x)"), "np.arcsin(x)");
        assert_eq!(to_python("ln(x) + exp(y)"), "np.log(x)+np.exp(y)");
        assert_eq!(to_python("log(x)"), "np.log10(x)");
        assert_eq!(to_python("min(2 m, 3 m)"), "np.minimum(2*m,3*m)");
        assert_eq!(to_python("sqrt(x^2 + y^2)"), "np.sqrt(x**2+y**2)");
    }

    #[test]
    fn test_generate_python_headers_and_bindings() {
        let ws = make_math_ws("a", "5 m");
        let code = generate_python(&ws);
        assert!(code.contains("import numpy as np"));
        assert!(code.contains("import pint"));
        assert!(code.contains("a = 5*m"));
        assert!(code.contains("print('a =', a)"));
    }

    #[test]
    fn test_header_is_headless_and_scipy_free() {
        let ws = make_math_ws("a", "1");
        let code = generate_python(&ws);
        assert!(code.contains("matplotlib.use(\"Agg\")"));
        assert!(code.contains("def _deriv"));
        assert!(code.contains("def _integ"));
        assert!(!code.contains("scipy"));
        assert!(!code.contains("plt.show"));
    }

    #[test]
    fn test_generate_python_skips_empty() {
        let ws = make_math_ws("a", "");
        let code = generate_python(&ws);
        assert!(!code.contains("# Math Region 1"));
    }

    #[test]
    fn test_generate_python_unnamed() {
        let ws = make_math_ws("", "2 + 2");
        let code = generate_python(&ws);
        assert!(code.contains("print(2+2)"));
    }

    #[test]
    fn test_generate_python_plot() {
        let mut ws = Worksheet::new("Test");
        let mut plot = crate::plot::PlotPane::default();
        plot.var = "x".to_owned();
        plot.expr = "sin(x)".to_owned();
        plot.x_min = 0.0;
        plot.x_max = 10.0;
        plot.samples = 100;

        ws.regions = vec![Region::Plot(plot)];

        let code = generate_python(&ws);
        assert!(code.contains("x = np.linspace(0, 10, 100)"));
        assert!(code.contains("y = np.sin(x)"));
        assert!(code.contains("plt.plot(x, y)"));
        assert!(code.contains("plt.savefig(\"plot_1.png\")"));
        assert!(code.contains("plt.close()"));
        assert!(!code.contains("plt.show"));
    }

    #[test]
    fn test_generate_python_handles_text_regions() {
        let mut ws = Worksheet::new("Test");
        ws.regions = vec![
            Region::Text("Hello World".to_string()),
            Region::Math(Expression::new("a", "5 m")),
        ];
        let code = generate_python(&ws);
        assert!(code.contains("# Hello World"));
        assert!(code.contains("a = 5*m"));
    }

    #[test]
    fn test_to_python_calculus() {
        assert_eq!(to_python("deriv(x^2, x)"), "_deriv(lambda x: x**2, globals().get(\"x\", 0.0))");
        assert_eq!(to_python("integ(x^2, x, 0, 3)"), "_integ(lambda x: x**2, 0, 3)");
    }

    #[test]
    fn test_plot_deriv_evaluates_over_range() {
        assert_eq!(to_python_ctx("deriv(x^2, x)", Some("x")), "_deriv(lambda x: x**2, x)");
        // deriv wrt a different variable still uses that variable's binding
        assert_eq!(to_python_ctx("deriv(t^2, t)", Some("x")), "_deriv(lambda t: t**2, globals().get(\"t\", 0.0))");
    }
}