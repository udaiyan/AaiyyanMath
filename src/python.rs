use crate::worksheet::Worksheet;
use crate::quantity::preprocess;
use regex::Regex;

pub fn generate_python(ws: &Worksheet) -> String {
    let mut code = String::new();

    // Header and imports
    code.push_str("# Auto-generated by AaiyyanMath\n");
    code.push_str("import math\n");
    code.push_str("import numpy as np\n");
    code.push_str("import matplotlib.pyplot as plt\n");
    code.push_str("import pint\n\n");

    // Unit definitions
    code.push_str("ureg = pint.UnitRegistry()\n");
    code.push_str("m = ureg.meter\n");
    code.push_str("s = ureg.second\n");
    code.push_str("kg = ureg.kilogram\n");
    code.push_str("A = ureg.ampere\n");
    code.push_str("K = ureg.kelvin\n");
    code.push_str("mol = ureg.mole\n");
    code.push_str("cd = ureg.candela\n");
    code.push_str("km = ureg.kilometer\n");
    code.push_str("cm = ureg.centimeter\n");
    code.push_str("mm = ureg.millimeter\n");
    code.push_str("g = ureg.gram\n");
    code.push_str("ms = ureg.millisecond\n");
    code.push_str("us = ureg.microsecond\n");
    code.push_str("ns = ureg.nanosecond\n");
    code.push_str("pi = math.pi\n");
    code.push_str("e = math.e\n\n");

    // Expressions
    for (i, expr) in ws.exprs.iter().enumerate() {
        if expr.input.trim().is_empty() { continue; }

        code.push_str(&format!("# Expression {}\n", i + 1));
        let py_input = to_python(&expr.input);

        if expr.label.trim().is_empty() {
            code.push_str(&format!("print({})\n", py_input));
        } else {
            code.push_str(&format!("{} = {}\n", expr.label, py_input));
            code.push_str(&format!("print('{} =', {})\n", expr.label, expr.label));
        }
        code.push('\n');
    }

    // Plot
    if !ws.plot.expr.trim().is_empty() {
        code.push_str("# Plot\n");
        let py_plot_expr = to_python(&ws.plot.expr);
        let var = &ws.plot.var;

        code.push_str(&format!("{} = np.linspace({}, {}, {})\n", var, ws.plot.x_min, ws.plot.x_max, ws.plot.samples));
        code.push_str(&format!("y = {}\n", py_plot_expr));

        code.push_str(&format!("plt.plot({}, y)\n", var));
        code.push_str("plt.grid(True)\n");
        code.push_str("plt.show()\n");
    }

    code
}

fn to_python(expr: &str) -> String {
    // 1. Use our existing preprocessor to insert `*` for units (e.g., "5 m" -> "5*m")
    let mut s = preprocess(expr);

    // 2. Convert `^` to `**` for Python exponentiation
    s = s.replace("^", "**");

    // 3. Map math functions to Numpy using a single regex pass
    // This ensures 'ln' doesn't become 'np.log' and then get corrupted by 'log' -> 'np.log10'
    let re = Regex::new(r"\b(sin|cos|tan|asin|acos|atan|sinh|cosh|tanh|ln|log|exp|sqrt|abs|floor|ceil|round|min|max)\(").unwrap();

    s = re.replace_all(&s, |caps: &regex::Captures| {
        let func = &caps[1];
        let py_func = match func {
            "sin" => "np.sin",
            "cos" => "np.cos",
            "tan" => "np.tan",
            "asin" => "np.arcsin",
            "acos" => "np.arccos",
            "atan" => "np.arctan",
            "sinh" => "np.sinh",
            "cosh" => "np.cosh",
            "tanh" => "np.tanh",
            "ln" => "np.log",
            "log" => "np.log10",
            "exp" => "np.exp",
            "sqrt" => "np.sqrt",
            "abs" => "np.abs",
            "floor" => "np.floor",
            "ceil" => "np.ceil",
            "round" => "np.round",
            "min" => "np.minimum",
            "max" => "np.maximum",
            _ => func,
        };
        format!("{}(", py_func)
    }).to_string();

    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::worksheet::Worksheet;

    #[test]
    fn test_to_python_basic_math() {
        assert_eq!(to_python("2 + 3 * 4"), "2+3*4");
        assert_eq!(to_python("a^2"), "a**2");
        assert_eq!(to_python("(a + b)^3"), "(a+b)**3");
    }

    #[test]
    fn test_to_python_units() {
        assert_eq!(to_python("5 m"), "5*m");
        assert_eq!(to_python("5 m / 2 s"), "5*m/2*s");
        assert_eq!(to_python("10 kg * 2"), "10*kg*2");
    }

    #[test]
    fn test_to_python_functions() {
        assert_eq!(to_python("sin(x)"), "np.sin(x)");
        assert_eq!(to_python("asin(x)"), "np.arcsin(x)");
        assert_eq!(to_python("ln(x) + exp(y)"), "np.log(x)+np.exp(y)");
        assert_eq!(to_python("log(x)"), "np.log10(x)");
        assert_eq!(to_python("min(2 m, 3 m)"), "np.minimum(2*m,3*m)");
        assert_eq!(to_python("sqrt(x^2 + y^2)"), "np.sqrt(x**2+y**2)");
    }

    #[test]
    fn test_generate_python_headers_and_bindings() {
        let mut ws = Worksheet::new("Test");
        ws.exprs[0].input = "5 m".to_owned();
        ws.exprs[1].input = "a / 2 s".to_owned();

        let code = generate_python(&ws);
        assert!(code.contains("import numpy as np"));
        assert!(code.contains("import pint"));
        assert!(code.contains("a = 5*m"));
        assert!(code.contains("print('a =', a)"));
        assert!(code.contains("b = a/2*s"));
    }

    #[test]
    fn test_generate_python_skips_empty() {
        let mut ws = Worksheet::new("Test");
        ws.exprs[0].input = "".to_owned(); // Empty
        let code = generate_python(&ws);
        assert!(!code.contains("# Expression 1")); // Should skip it entirely
    }

    #[test]
    fn test_generate_python_unnamed() {
        let mut ws = Worksheet::new("Test");
        ws.exprs[0].label = "".to_owned(); // Unnamed
        ws.exprs[0].input = "2 + 2".to_owned();
        let code = generate_python(&ws);
        assert!(code.contains("print(2+2)"));
    }

    #[test]
    fn test_generate_python_plot() {
        let mut ws = Worksheet::new("Test");
        ws.plot.expr = "sin(x)".to_owned();
        ws.plot.var = "x".to_owned();
        ws.plot.x_min = 0.0;
        ws.plot.x_max = 10.0;
        ws.plot.samples = 100;

        let code = generate_python(&ws);
        assert!(code.contains("x = np.linspace(0, 10, 100)"));
        assert!(code.contains("y = np.sin(x)"));
        assert!(code.contains("plt.plot(x, y)"));
    }
}